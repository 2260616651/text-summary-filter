"""判定基准与三道 agent 提示词的通用模板生成器。

不包含任何特定项目内容；特定项目的判定对象定义全部由 --subject 等参数注入。
由 run_pipeline.py 在 S3 阶段调用，产出：
  - 筛选_判定基准.md      三道 agent 唯一共用标准
  - agent1_prompt.md      第 1 道 宽松初筛
  - agent2_prompt.md      第 2 道 极宽松抢救
  - agent3_prompt.md      第 3 道 终审放回
主线程按这三个文件直接派串行前台 agent，不再手工拼提示词。
"""


def render_criterion(subject: str, subject_desc: str, keep_categories: str,
                     extra_notes: str = "") -> str:
    """生成五节结构的统一判定基准。"""
    subject = subject.strip() or "目标项目"
    desc = subject_desc.strip() or "（未提供项目描述，请由主线程在开场询问阶段向用户确认后补充，或据源文档开头自行归纳并标注「(AI 推论)」。）"
    cats = keep_categories.strip() or (
        "| 类别 | 说明 |\n|---|---|\n"
        "| 机制/系统设定 | 玩法规则、子系统、流程定义 |\n"
        "| 数值/参数/公式 | 硬数据、编号、阈值、坐标、版本、配比 |\n"
        "| 选型与兼容 | 组件/依赖/版本清单与适配方案 |\n"
        "| 工程与规划 | 开发次序、模块清单、架构、发布与运维 |\n"
        "| 背景与素材 | 作为设计依据、素材、灵感来源引入的外部知识 |\n"
        "| 作者规划 | 用于说明项目周期/分工/资源约束的背景信息 |"
    )
    extra = ("\n## 六、本次补充约定\n\n" + extra_notes.strip() + "\n") if extra_notes.strip() else ""
    return f"""# {subject} · 内容筛选判定基准（三道校验共用）

> 本文件是三个判定 agent 的**唯一共同标准**。所有 agent 必须先完整读完本基准，再开始判定。
> 目标：只保留属于「{subject}」的设计条目，剔除**毫无关联**的数据；用三道独立校验防止误删。
> 本文件由 `pipeline_templates.py` 自动生成，不得由任何 agent 改写。

---

## 一、判定对象定义

{desc}

因此，**凡下列内容都属于设计条目（应保留）**：

{cats}

> **关键**：汇总整理稿里看似「杂项」的内容（人生规划、现实新闻、AI 对话、别的软件名、外部科普）往往是被当作**设计依据、素材、开发背景或工具链**收进来的，属于有关联。默认保留。

---

## 二、什么才算「毫无关联」（唯一可剔除标准）

必须**同时满足**以下三条，才可判定为「毫无关联」：

1. **不含**任何与「{subject}」相关的实质信息；
2. **不是**上述任一「设计条目」类别，也**不能**作为设计依据、素材、背景、工具链或开发流程的一部分被解释；
3. 属于**其他项目、其他话题、或纯文档工程残留**，例如：
   - 与本项目无关的其他软件项目内容中完全没被用于本项目的部分；
   - 纯**文档处理流程元信息**：区块/分卷标记、来源文件名标注、合并块标题、行映射说明、压缩/去重/切分记录、指纹校验记录；
   - 纯粹的空白行、分隔符、页码。

**边界模糊一律不得剔除。** 判定原则：

- **拿不准 → 不当作「毫无关联」**（宁可留在主文档，也不可误删）。
- 一行里只要**夹带任何**设计信息（哪怕大半是别的），**整行保留**，不得拆行、不得只删半句。
- 章节标题、`###` 小标题、`【…】` 分组标记、`- ` 条目起始符、来源/批次标注，**属于文档骨架，一律保留**，即使其文字本身信息量低。
- 来源标注若与标题/正文同处一行，按「整行保留」处理。

---

## 三、三道校验的分工与阈值（各 agent 只做自己那一道）

| 道次 | 角色 | 输入 | 判定阈值 | 输出 |
|---|---|---|---|---|
| **第 1 道** | 初判筛除 | 母本全量（判定视图 + 可回查原文） | **宽松初筛**：看上去与设计无关就拎出；允许误伤，后面两道负责捞回 | `agent1_result.json` |
| **第 2 道** | 复核抢救 | **仅**第 1 道产出的文档 A | **极宽松**：只要存在**任何**关联线索（哪怕间接、只是作为文档骨架/来源标注/编号段说明/批次标记）一律捞出；宁可错捞不可漏 | `agent2_result.json` |
| **第 3 道** | 终审放回 | 文档 A + 文档 B | **终审**：拿不准→放回；逐条独立回查，可否决前两道 | `agent3_result.json` |

- 第 2 道**不得**重新通读母本全文、不得引入 A 之外的新条目；它的职责是**给第 1 道纠错**。
  但允许按行号回查母本**前后文**，以判断某行是否「统领下方成片设计条目」。
- 第 3 道是**最终裁决**，必须逐条覆盖 B 的每一条，并复核 A 中未被捞走的条目。

---

## 四、输出硬性要求（三个 agent 共同遵守）

1. **只输出行号清单 + 理由**，原文由脚本按行号从母本原样抽取生成新文档——**严禁手工复写、改写、缩略、截断任何原文**。
2. 行号必须是母本的**物理行号**，与 `筛选_判定视图.txt` 的 `L<n>|` 一一对应。
3. 对拿不准的行，用 Read 按行号回查母本**完整原文**后再判断，不得凭截首臆断。
4. 每一条判定都必须附**具体理由**（不得只写「无关」「有关」）。
5. 输出为 UTF-8 JSON，写到指定路径，格式：
   ```json
   {{"items":[{{"line":123,"reason":"……","verdict":"……"}}]}}
   ```
   第 3 道另需 `summary.final_remove_lines` / `summary.final_restore_lines` / `review_remaining`，
   且 remove 与 restore **互斥、并集恰为 A 的初判全集**。
6. **不许修改母本、不许修改本基准、不许修改任何其他既有文档**；只新建自己那一道指定的输出文件。
7. 完成后报告：共检查多少行、拎出多少行、放弃多少行（及原因）。
8. **只回一行确认给主线程**，不回正文、不粘贴块内容。

---

## 五、零丢失底线

- 三个新文档中的每一条原文，都必须与母本对应行**逐字节一致**。
- 删除「设计文字内容」是绝对红线；空行/分隔符是否剔除由第 3 道最终确认。
- 全部流程结束后由脚本核验：原文取自母本、行号无越界、无重复、无遗漏、
  剔除集 ∪ 放回集 = 初判全集且互斥、三类硬数据指纹集合层 0 缺失。
- 已达零丢失下限（压缩比 ≥0.9 或输出 ≥ 输入、连续数轮无下降）时**停止压缩并向用户报告**，禁止为凑篇幅强压。
{extra}"""


_AGENT_COMMON = """## 通用执行纪律（三道共同）

- **严格串行、前台执行**：不要启动其他 agent；本环境后台 agent 会被回收导致零产出。
- **只回一行确认**：不把正文、摘要、原文回给主线程，避免上下文臃肿。
- 只新建自己那一道指定的 JSON 文件，**不得修改母本、判定基准、其他 agent 的产出或任何既有文件**。
- 判定视图是截断的；拿不准就用 Read 按行号回查母本完整原文，不凭截首臆断。
- 每条判定附**具体理由**；只输出行号 + 理由 + verdict，**严禁手工复写原文**（原文由脚本零改写抽取）。
- 行号为母本物理行号，唯一、升序、无越界、reason 非空。

### 写盘后自检（硬性，不可省略）
JSON 落盘后**重新读回自己写的文件**逐项核对，全通过才允许回报完成；不通过就修正后重写，
**绝不把带错的文件交给下一道**：
1. 文件是合法 UTF-8 JSON，顶层含 `items` 数组（第 3 道另含 `summary` / `review_remaining`）；
2. 每条 `line` 是整数、在母本行数范围内、`items` 内无重复、按升序排列；
3. 每条 `reason` 非空且是具体理由（不是「无关」「有关」这类空话）；
4. **本道的输入依赖边界**没破：第 2 道每个行号都能在文档 A 里找到；
   第 3 道 `items` 恰好覆盖 B 全部行号，且 `summary.final_remove_lines` 与
   `final_restore_lines` 互斥、并集恰为 A 的初判全集。
回报的一行确认里附「自检 PASS」。
"""


def render_agent_prompt(pass_no: int, *, workdir: str, subject: str,
                        criterion: str, view: str, source: str,
                        doc_a: str = "", doc_b: str = "", out_json: str = "",
                        think_depth: str = "medium") -> str:
    """生成某一道的完整提示词；路径参数全部由编排器注入。

    think_depth（Q0 本地模型分支）：low 追加「只给结论、不展开推理」、
    high 追加「可展开推理」一行强度指令；medium 保持现有行为不变。
    """
    common = _AGENT_COMMON
    if think_depth == "low":
        common += "\n\n【思考强度 low】只给结论、不展开推理，完成后只回一行确认，禁止并发展开。"
    elif think_depth == "high":
        common += "\n\n【思考强度 high】可展开推理，逐条给出判断依据与回查过程。"
    if pass_no == 1:
        return f"""你是「第 1 道：宽松初筛」agent。任务：从「{subject}」的汇总文档中，把**看上去与设计毫无关联**的条目拎出来。{common}

## 必读（按顺序）
1. 判定基准（唯一标准，**完整读完**）：`{criterion}`
2. 判定视图（全量行，分段读完，不要跳读）：`{view}`
3. 母本原文（按行号回查）：`{source}`

## 阈值（第 1 道：宽松初筛）
- 拎出 = 看上去与「{subject}」设计毫无关联的行。**允许误伤**，后面两道负责捞回。
- **不得拎出**：任何含项目/机制/数值/开发规划/发布运营/世界观/背景规划等实质信息的行；
  章节标题、`###` 小标题、`【…】` 分组标记、`- ` 起始符等文档骨架。
- **一行里只要夹带任何设计信息，整行保留**，不得拆行、不得只删半句。
- 边界模糊 → **不拎出**。
- 典型可拎出的：与项目无关的其他项目内容、纯文档工程残留（区块/分卷标记、来源文件名标注、
  合并块标题、压缩/去重/切分/行映射/指纹校验记录）、纯空白行/分隔符/页码。
- **重要**：汇总整理稿里看似杂项的内容（人生规划、现实新闻、AI 对话、别的软件名、外部科普）
  多半是作为设计依据/素材/开发背景/工具链收进来的，**属于有关联，不得拎出**。

## 输出
写 UTF-8 JSON：`{out_json}`
```json
{{"items":[{{"line":123,"reason":"具体理由，不得只写『无关』","verdict":"与设计无关"}}]}}
```
完成后**只回一行确认**：文件路径 + 已读视图行数 + 拎出条数 + 放弃拎出的典型例子 3~5 个。
如实工作，不要编造行号；结果为 0 条也要写 `{{"items":[]}}`。
"""
    if pass_no == 2:
        return f"""你是「第 2 道：极宽松抢救」agent。任务：**给第 1 道纠错**——把被误判为「无关」但其实与「{subject}」**存在任何关联**的条目全部捞出来。{common}

## 必读（按顺序）
1. 判定基准（唯一标准，完整读完）：`{criterion}`
2. **你的唯一输入文档 A**：`{doc_a}`（第 1 道拎出的全部条目）
3. 母本原文（**仅**按行号回查前后文）：`{source}`

## 阈值（第 2 道：极宽松）
- **只要存在任何关联线索一律捞出**：哪怕只是间接、只是作为文档骨架/来源标注/编号段说明/
  合并批次标记、只是提到项目名、只是标明某批设计条目的出处。
- **宁可错捞，不可漏掉**。你的职责不是替第 1 道辩护，而是尽力抢救。
- **关键动作**：对每条被拎出的行，用 Read 回看它在母本里的**前后各 3~8 行上下文**。
  一个「来源标注」或「批次标题」是否有关联，取决于它**所统领的下方内容**是不是设计条目。
  不要只看孤立的一行。
- 不得引入文档 A 之外的任何新行号。

## 输出
写 UTF-8 JSON：`{out_json}`
```json
{{"items":[{{"line":123,"reason":"具体关联线索，不得只写『有关』","verdict":"有关联，建议捞回"}}]}}
```
完成后**只回一行确认**：已读 A 的条目数 + 回查上下文次数 + 捞出条数 + 没捞的条数与理由分类。
结果为 0 条也要写 `{{"items":[]}}`。
"""
    if pass_no == 3:
        return f"""你是「第 3 道：终审裁决」agent，三道校验的**最终裁决者**，你的结论直接决定哪些行从最终文档剔除。{common}

## 必读（按顺序）
1. 判定基准（唯一标准，完整读完）：`{criterion}`
2. 文档 A（第 1 道初判全集）：`{doc_a}`
3. 文档 B（第 2 道捞出的关联条目）：`{doc_b}`
4. 母本原文（终审依据）：`{source}` —— **必须对 B 中每条逐条回查前后文**，独立核验，不要只信第 2 道的结论。

## 裁决任务（两部分都要做）
**甲、对 B 的每一条逐条裁决**，二选一 + 具体依据：
- `放回主文档`：确认有关联、或删它会造成信息/骨架/出处丢失、或边界模糊；
- `维持剔除`：确证毫无关联且删除不损失任何设计信息。
**拿不准 → 放回**（零丢失是硬底线）。你可以**不同意**前两道的任何结论，但必须写明理由。

**乙、复核 A 中未被捞走的条目**，判断是否有被错留的（其实有关联、该放回）。
注意这些条目通常不含设计文字（空行/分隔符），删除不造成设计信息丢失；
但请从「最终文档可读性/结构完整性」角度给一句明确建议
（例如建议生成侧在章节切换处补规范空行，而非把空行行号放回——放回会破坏「仅按行号抽取」的零改写机制）。

## 输出
写 UTF-8 JSON：`{out_json}`
```json
{{
  "items": [{{"line":123,"verdict":"放回主文档","reason":"具体依据……"}}],
  "review_remaining": {{"count":81,"conclusion":"维持剔除","reason":"……","rescue_lines":[]}},
  "summary": {{
    "final_remove_lines": [2,3,4],
    "final_restore_lines": [1,50],
    "note": "最终结论说明"
  }}
}}
```
硬校验：`items` 必须恰好覆盖 B 全部行号；`final_remove_lines` 与 `final_restore_lines`
**互斥且并集恰为 A 的初判全集**；行号无越界；reason 非空。
完成后**只回一行确认**：B 逐条结论摘要 + 81 条复核结论 + 剔除/放回条数（合计应 = A）+ 零丢失结论。
"""
    raise ValueError("pass_no 只能是 1/2/3")
